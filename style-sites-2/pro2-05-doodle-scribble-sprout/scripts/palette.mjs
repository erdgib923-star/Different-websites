// Generates src/styles/tokens.css from palette.config.mjs.
// Every colour is written as an in-gamut OKLCH custom property, with a hex fallback
// inside `@supports not (color: oklch(0 0 0))` for older browsers.
// Run: npm run palette
import { writeFileSync, readFileSync, existsSync } from 'node:fs';
import { fileURLToPath, pathToFileURL } from 'node:url';
import { dirname, resolve } from 'node:path';
import { gamutMap, oklchToSrgb, srgbToHex, fmt } from './color.mjs';

export const STEPS = [50, 100, 200, 300, 400, 500, 600, 700, 800, 900, 950];
const DEFAULT_L = [0.975, 0.94, 0.88, 0.8, 0.71, 0.62, 0.54, 0.46, 0.38, 0.3, 0.22];
const CHROMA_CURVE = [0.12, 0.25, 0.5, 0.75, 0.92, 1, 0.97, 0.88, 0.76, 0.62, 0.48];
const NEUTRAL_CURVE = [0.45, 0.55, 0.7, 0.85, 1, 1, 1, 1, 1, 1, 0.95];

const root = resolve(dirname(fileURLToPath(import.meta.url)), '..');

export async function loadConfig() {
  return (await import(pathToFileURL(resolve(root, 'palette.config.mjs')).href)).default;
}

const triple = (L, C, H) => {
  const c = gamutMap(L, C, H);
  return { L, C: c, H, css: `oklch(${fmt(L)} ${fmt(c, 4)} ${fmt(H, 1)})`, hex: srgbToHex(oklchToSrgb(L, c, H)) };
};

/** Resolve the whole palette into { primitives: Map, themes: {name: Map} } of colour triples. */
export function resolvePalette(cfg) {
  const primitives = new Map();
  for (const [name, r] of Object.entries(cfg.ramps)) {
    const Ls = r.lightness ?? DEFAULT_L;
    const curve = r.neutral ? NEUTRAL_CURVE : CHROMA_CURVE;
    STEPS.forEach((step, i) => primitives.set(`${name}-${step}`, triple(Ls[i], r.chroma * curve[i], r.hue)));
  }
  for (const [name, v] of Object.entries(cfg.colors ?? {})) primitives.set(name, triple(...v));

  const themes = {};
  for (const [tname, theme] of Object.entries(cfg.themes)) {
    const map = new Map();
    for (const [token, v] of Object.entries(theme.tokens)) {
      if (Array.isArray(v)) map.set(token, { ...triple(...v), raw: true });
      else if (primitives.has(v)) map.set(token, { ...primitives.get(v), ref: v });
      else throw new Error(`Theme ${tname}: token ${token} references unknown colour "${v}"`);
    }
    themes[tname] = map;
  }
  return { primitives, themes };
}

export function renderCss(cfg) {
  const { primitives, themes } = resolvePalette(cfg);
  const out = [];
  out.push('/* GENERATED by scripts/palette.mjs from palette.config.mjs. Do not edit by hand:');
  out.push('   change the config, then run `npm run palette`. */', '');
  out.push(':root {');
  for (const [k, v] of primitives) out.push(`  --${k}: ${v.css};`);
  out.push('}', '');
  out.push('@supports not (color: oklch(0 0 0)) {', '  :root {');
  for (const [k, v] of primitives) out.push(`    --${k}: ${v.hex};`);
  out.push('  }', '}', '');
  for (const [tname, map] of Object.entries(themes)) {
    const sel = cfg.themes[tname].selector;
    out.push(`/* theme: ${tname} */`, `${sel} {`);
    if (cfg.themes[tname].colorScheme) out.push(`  color-scheme: ${cfg.themes[tname].colorScheme};`);
    for (const [k, v] of map) out.push(`  --${k}: ${v.ref ? `var(--${v.ref})` : v.css};`);
    out.push('}');
    const raws = [...map].filter(([, v]) => v.raw);
    if (raws.length) {
      out.push('@supports not (color: oklch(0 0 0)) {', `  ${sel} {`);
      for (const [k, v] of raws) out.push(`    --${k}: ${v.hex};`);
      out.push('  }', '}');
    }
    out.push('');
  }
  return out.join('\n');
}

export const TOKENS_PATH = resolve(root, 'src/styles/tokens.css');

if (import.meta.url === pathToFileURL(process.argv[1]).href) {
  const cfg = await loadConfig();
  const css = renderCss(cfg);
  const changed = !existsSync(TOKENS_PATH) || readFileSync(TOKENS_PATH, 'utf8') !== css;
  writeFileSync(TOKENS_PATH, css);
  console.log(`${changed ? 'Wrote' : 'Unchanged'} ${TOKENS_PATH}`);
}
