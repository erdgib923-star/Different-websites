// Generates the CSS colour tokens from scripts/palette.config.mjs.
// Output: hex fallbacks first, OKLCH inside @supports, display-p3 accent highlights inside @media (color-gamut: p3).
import { writeFileSync, mkdirSync } from 'node:fs';
import { dirname, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';
import { ramp, toHex, fmt, toP3String, clampChroma, inSrgb, inP3 } from './color.mjs';
import config from './palette.config.mjs';

const root = resolve(dirname(fileURLToPath(import.meta.url)), '..');
const raw = []; // { name, L, C, H }

for (const [name, opts] of Object.entries(config.ramps)) {
  for (const s of ramp(opts)) raw.push({ name: `${name}-${s.step}`, ...s });
}
for (const [name, [L, C, H]] of Object.entries(config.extra ?? {})) {
  raw.push({ name, L, C: clampChroma(L, C, H, inSrgb), H });
}

const semantic = Object.entries(config.semantic).map(([name, ref]) => {
  const v = (r) => (r.startsWith('raw:') ? r.slice(4) : `var(--${r})`);
  if (typeof ref === 'object') return `  --${name}: light-dark(${v(ref.light)}, ${v(ref.dark)});`;
  return `  --${name}: ${v(ref)};`;
});

const p3 = Object.entries(config.p3 ?? {}).map(([name, [L, C, H]]) => {
  const cS = clampChroma(L, C, H, inSrgb);
  const cP = clampChroma(L, C, H, inP3);
  return { name, L, H, cS, cP };
});

const css = `/* AUTO-GENERATED by scripts/build-tokens.mjs from scripts/palette.config.mjs. Do not edit by hand. */
/* 1. hex fallbacks (sRGB, chroma-reduced gamut mapping) */
:root {
${raw.map((c) => `  --${c.name}: ${toHex(c.L, c.C, c.H)};`).join('\n')}
${p3.map((c) => `  --${c.name}: ${toHex(c.L, c.cS, c.H)};`).join('\n')}
}

/* 2. OKLCH values for browsers that support them */
@supports (color: oklch(0% 0 0)) {
  :root {
${raw.map((c) => `    --${c.name}: ${fmt(c.L, c.C, c.H)};`).join('\n')}
${p3.map((c) => `    --${c.name}: ${fmt(c.L, c.cS, c.H)};`).join('\n')}
  }
}

/* 3. wide-gamut accent highlights only */
@media (color-gamut: p3) {
  @supports (color: color(display-p3 0 0 0)) {
    :root {
${p3.map((c) => `      --${c.name}: ${toP3String(c.L, c.cP, c.H)};`).join('\n')}
    }
  }
}

/* 4. semantic tokens (components use only these) */
:root {
${semantic.join('\n')}
}
`;

const out = resolve(root, config.out);
mkdirSync(dirname(out), { recursive: true });
writeFileSync(out, css);
console.log(`tokens: wrote ${raw.length + p3.length} reference + ${semantic.length} semantic tokens -> ${config.out}`);
